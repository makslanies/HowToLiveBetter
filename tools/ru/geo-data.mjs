export function stats() {
  const secs = parseBook(); const all = secs.flatMap((s) => s.entries);
  return { secs, all, entries: all.length, sections: secs.length, A: all.filter((e) => e.grade === 'A').length, B: all.filter((e) => e.grade === 'B').length, C: all.filter((e) => e.grade === 'C').length, disputes: all.filter((e) => e.dispute).length, russia: all.filter((e) => e.ru).length, prices: all.filter((e) => e.price).length };
}

// склонение числительного с существительным: 1→one, 2-4→few, 5-20→many (и 11-14 всегда many)
export const plural = (n, one, few, many) => {
  const n10 = n % 10, n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return `${n} ${one}`;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return `${n} ${few}`;
  return `${n} ${many}`;
};
export const pluralPunkt = (n) => plural(n, 'пункт', 'пункта', 'пунктов');

